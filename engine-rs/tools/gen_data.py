"""Converts the data tables of the former C++ engine (lotus/data/*) to Rust.

The C++ tables were the source of truth until the engine moved to Rust; this script turned them
into the files under engine-rs/src/data/ and is kept so the conversion can be re-run and audited.
The C++ files no longer exist in the tree, so read them from the last commit that has them:

    engine-rs/tools/gen_data.py --git 09516fd            # writes engine-rs/src/data/*.rs
    engine-rs/tools/gen_data.py --src path/to/lotus/data # or from a directory

Converted tables:
  case_data.cpp            -> case.rs     (lower/upper pairs, letters)
  charset_data.cpp         -> charset.rs  (16 legacy charset tables)
  vikey_autoswitch_data.h  -> vikey_autoswitch.rs (Vikey word scores, GPL-3.0, header kept)
  vikey_bigram_data.h      -> vikey_bigram.rs     (Vikey word pairs, GPL-3.0, header kept)
The small structural tables (vowels, mark families, spelling sequences, input method
definitions) are written by hand in src/data/mod.rs and checked by the unit tests.
"""

import argparse
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(HERE, "..", "src", "data")

GENERATED = (
    "// Generated by engine-rs/tools/gen_data.py from the former C++ table lotus/data/{src}."
    " Do not edit.\n"
)


class Source:
    def __init__(self, args):
        self.args = args

    def read(self, name):
        if self.args.git:
            top = ["git", "rev-parse", "--show-toplevel"]
            root = subprocess.check_output(top, cwd=HERE, text=True).strip()
            show = ["git", "show", f"{self.args.git}:lotus/data/{name}"]
            return subprocess.check_output(show, cwd=root).decode("utf-8")
        with open(os.path.join(self.args.src, name), encoding="utf-8") as handle:
            return handle.read()


def strip_comments(text):
    out = []
    i = 0
    n = len(text)
    while i < n:
        c = text[i]
        if c in "\"'":
            # Copy a literal verbatim (escapes included).
            j = i + 1
            while j < n and text[j] != c:
                j += 2 if text[j] == "\\" else 1
            out.append(text[i : j + 1])
            i = j + 1
        elif text.startswith("//", i):
            j = text.find("\n", i)
            i = n if j < 0 else j
        elif text.startswith("/*", i):
            j = text.find("*/", i)
            i = n if j < 0 else j + 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def unescape(body, wide):
    """Decodes a C++ literal body: a list of code points (wide) or of bytes (narrow, UTF-8)."""
    out = []
    i = 0
    n = len(body)
    simple = {
        "n": 10,
        "t": 9,
        "r": 13,
        "\\": 92,
        "'": 39,
        '"': 34,
        "?": 63,
        "a": 7,
        "b": 8,
        "f": 12,
        "v": 11,
    }

    def put(code_point):
        if wide:
            out.append(code_point)
        else:
            out.extend(chr(code_point).encode("utf-8"))

    while i < n:
        c = body[i]
        if c != "\\":
            put(ord(c))
            i += 1
            continue
        e = body[i + 1]
        if e in simple:
            put(simple[e])
            i += 2
        elif e == "u":
            put(int(body[i + 2 : i + 6], 16))
            i += 6
        elif e == "U":
            put(int(body[i + 2 : i + 10], 16))
            i += 10
        elif e == "x":
            m = re.match(r"[0-9a-fA-F]+", body[i + 2 :])
            out.append(int(m.group(0), 16))
            i += 2 + len(m.group(0))
        elif e in "01234567":
            m = re.match(r"[0-7]{1,3}", body[i + 1 :])
            out.append(int(m.group(0), 8))  # a raw byte (narrow) or code unit (wide)
            i += 1 + len(m.group(0))
        else:
            raise ValueError(f"unknown escape \\{e}")
    return out


TOKEN = re.compile(r"""(U?)'((?:\\.|[^'\\])+)'|(U?)"((?:\\.|[^"\\])*)"|([{}])""", re.S)


def tokens(text):
    """Yields ('{'|'}', None) and ('char'|'str'|'wstr', value) in source order."""
    for m in TOKEN.finditer(strip_comments(text)):
        if m.group(2) is not None:
            cps = unescape(m.group(2), True)
            assert len(cps) == 1, m.group(0)
            yield ("char", cps[0])
        elif m.group(4) is not None:
            if m.group(3) == "U":
                yield ("wstr", unescape(m.group(4), True))
            else:
                yield ("str", bytes(unescape(m.group(4), False)))
        else:
            yield (m.group(5), None)


def rust_char(cp):
    if not chr(cp).isprintable() or chr(cp) in "'\\" or cp == 0xAD:
        return f"'\\u{{{cp:04X}}}'"
    return f"'{chr(cp)}'"


def rust_str(data):
    """A Rust &str literal of UTF-8 bytes (escaping controls and invisible characters)."""
    text = data.decode("utf-8")
    out = []
    for ch in text:
        cp = ord(ch)
        if ch in '"\\':
            out.append("\\" + ch)
        elif cp < 0x20 or cp == 0x7F or (0x80 <= cp < 0xA0) or cp == 0xAD or not ch.isprintable():
            out.append(f"\\u{{{cp:04X}}}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def rust_bytes(data, width=120):
    """A Rust byte string literal, wrapped with line continuations."""
    lines = []
    line = []
    length = 0
    for b in data:
        if b == 0:
            piece = "\\0"
        elif b == 9:
            piece = "\\t"
        elif b == 0x22:
            piece = '\\"'
        elif b == 0x5C:
            piece = "\\\\"
        elif 0x20 <= b < 0x7F:
            piece = chr(b)
        else:
            piece = f"\\x{b:02x}"
        line.append(piece)
        length += len(piece)
        if length >= width and b == 0:
            lines.append("".join(line))
            line = []
            length = 0
    if line:
        lines.append("".join(line))
    return 'b"' + "\\\n".join(lines) + '"'


def rust_array(values, per_line=40):
    rows = (values[i : i + per_line] for i in range(0, len(values), per_line))
    return "\n".join("    " + ", ".join(str(v) for v in row) + "," for row in rows)


def gen_case(src):
    text = src.read("case_data.cpp")

    def pairs(name):
        out = []
        pending = []
        depth = 0
        for kind, value in tokens(text[text.index(name) :]):
            if kind == "{":
                depth += 1
            elif kind == "}":
                depth -= 1
                if depth == 0:
                    break
            elif kind == "char":
                pending.append(value)
                if len(pending) == 2:
                    out.append(tuple(pending))
                    pending = []
        return out

    lower_upper = pairs("kLowerUpperData =")
    upper_lower = pairs("kUpperLowerData =")
    letters = []
    seen_letters = False
    for kind, value in tokens(text[text.index("kLettersView =") :]):
        if kind == "wstr":
            letters.extend(value)
            seen_letters = True
        elif kind == "str" and seen_letters:
            # An unprefixed literal next to U"..." is concatenated as UTF-32 too.
            letters.extend(ord(c) for c in value.decode("utf-8"))
        elif seen_letters:
            break
    assert lower_upper == sorted(lower_upper)
    assert upper_lower == sorted(upper_lower)
    assert letters == sorted(letters)

    out = [
        GENERATED.format(src="case_data.cpp"),
        "//! Case pairs and letters of the case map, sorted for binary search.\n",
    ]
    for name, table in (("LOWER_UPPER", lower_upper), ("UPPER_LOWER", upper_lower)):
        out.append(f"pub static {name}: [(char, char); {len(table)}] = [")
        for i in range(0, len(table), 10):
            row = table[i : i + 10]
            out.append("    " + " ".join(f"({rust_char(a)}, {rust_char(b)})," for a, b in row))
        out.append("];\n")
    out.append(f"pub static LETTERS: [char; {len(letters)}] = [")
    for i in range(0, len(letters), 20):
        out.append("    " + " ".join(f"{rust_char(c)}," for c in letters[i : i + 20]))
    out.append("];")
    return "\n".join(out) + "\n"


CHARSETS = """Unicode Bhkcm1 Bhkcm2 NcrDecimal NcrHex Tcvn3Abc Utf8 UnicodeCStringDecimal
UnicodeCStringHex UnicodeCombining Viqr Viscii VniWindows Vps VietwareFull VietwareX
Windows1258""".split()


def gen_charset(src):
    text = src.read("charset_data.cpp")
    tables = []
    current = None
    pending = []
    depth = 0
    for kind, value in tokens(text[text.index("kCharsetTables =") :]):
        if kind == "{":
            depth += 1
            if depth == 3:
                current = []
        elif kind == "}":
            if depth == 3:
                tables.append(current)
                current = None
            depth -= 1
            if depth == 0:
                break
        elif kind == "char":
            pending = [value]
        elif kind == "str":
            current.append((pending[0], value))
            pending = []
    assert len(tables) == len(CHARSETS), len(tables)
    out = [
        GENERATED.format(src="charset_data.cpp"),
        "//! Legacy charset tables, indexed like `Charset`; each one is sorted by code point.",
        "//! The C++ tables were `std::unordered_map`s built from an initializer list, so the"
        " first",
        "//! entry of a duplicated code point won; the duplicates are dropped the same way here.\n",
        "pub static TABLES: [&[(char, &str)]; 17] = [",
    ]
    for name, table in zip(CHARSETS, tables):
        seen = {}
        for cp, value in table:
            if cp in seen:
                print(
                    f"note: {name}: duplicate U+{cp:04X}, keeping the first value",
                    file=sys.stderr,
                )
                continue
            seen[cp] = value
        out.append(f"    // {name}")
        out.append("    &[")
        for cp in sorted(seen):
            out.append(f"        ({rust_char(cp)}, {rust_str(seen[cp])}),")
        out.append("    ],")
    out.append("];")
    return "\n".join(out) + "\n"


def c_arrays(text):
    """name -> bytes (char arrays) or list of ints (number arrays) of a Vikey data header."""
    result = {}
    ctypes = "char|unsigned int|signed char|unsigned char|int"
    decl = rf"static const ({ctypes}) (\w+)(\[\d*\])? =\s*(.*?);"
    for m in re.finditer(decl, text, re.S):
        ctype, name, _, init = m.groups()
        if ctype == "char":
            literals = re.findall(r'"((?:\\.|[^"\\])*)"', init)
            data = b"".join(bytes(unescape(s, False)) for s in literals)
            result[name] = data + b"\0"  # the implicit terminator of the C array
        elif ctype == "int" and not m.group(3):
            result[name] = int(init)
        else:
            result[name] = [int(v) for v in re.findall(r"-?\d+", init)]
    return result


def gen_vikey(src, name, arrays):
    text = src.read(name)
    data = c_arrays(text)
    header = []
    for line in text.splitlines():
        if not line.startswith("//"):
            break
        header.append(line)
    out = [
        "\n".join(header),
        "//\n// Converted to Rust by engine-rs/tools/gen_data.py from lotus/data/"
        f"{name}; the content is unchanged.",
        "// Each word list is one buffer of NUL terminated words, sorted byte-wise like strcmp,"
        " with the",
        "// start offset of every word and its value.\n",
    ]
    for rust_name, c_name, rust_type in arrays:
        value = data[c_name]
        if isinstance(value, bytes):
            out.append(f"pub static {rust_name}: &[u8] = {rust_bytes(value)};\n")
        else:
            out.append(
                f"pub static {rust_name}: [{rust_type}; {len(value)}] = [\n"
                f"{rust_array(value)}\n];\n"
            )
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--git", help="read lotus/data from this git revision")
    group.add_argument("--src", help="read the C++ tables from this directory")
    parser.add_argument(
        "--out", default=OUT_DIR, help="output directory (default: engine-rs/src/data)"
    )
    args = parser.parse_args()
    src = Source(args)
    os.makedirs(args.out, exist_ok=True)
    files = {
        "case.rs": gen_case(src),
        "charset.rs": gen_charset(src),
        "vikey_autoswitch.rs": gen_vikey(
            src,
            "vikey_autoswitch_data.h",
            [
                ("VN_WORDS", "kAutoSwitchVnWords", "u8"),
                ("VN_OFFSETS", "kAutoSwitchVnOffsets", "u32"),
                ("VN_SCORES", "kAutoSwitchVnScores", "i8"),
                ("EN_WORDS", "kAutoSwitchEnWords", "u8"),
                ("EN_OFFSETS", "kAutoSwitchEnOffsets", "u32"),
                ("EN_SCORES", "kAutoSwitchEnScores", "i8"),
            ],
        ),
        "vikey_bigram.rs": gen_vikey(
            src,
            "vikey_bigram_data.h",
            [
                ("KEYS", "kBigramKeys", "u8"),
                ("OFFSETS", "kBigramOffsets", "u32"),
                ("LOG_COUNTS", "kBigramLogCounts", "u8"),
            ],
        ),
    }
    for filename, content in files.items():
        with open(os.path.join(args.out, filename), "w", encoding="utf-8") as handle:
            handle.write(content)
        print(f"wrote {os.path.join(args.out, filename)}")


if __name__ == "__main__":
    main()
