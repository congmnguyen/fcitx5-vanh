"""Builds src/data/tech_english.rs: how common English words are in technical text.

The Vikey English list counts words in film subtitles, where "host", "docs" or "config" are rare.
This counts the words of the English manual pages installed on the build machine (sections 1, 5,
7, 8: commands, file formats, overviews, administration) on the same scale as Vikey,
10*log10(occurrences per million), keeping words seen at least MIN_COUNT times.

Usage: gen_tech_english.py [MAN_DIR] > src/data/tech_english.rs
"""
import collections, gzip, math, os, re, sys

MAN = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/man"
MIN_COUNT = 20
WORD = re.compile(r"[A-Za-z]+")

def text_of(path):
    raw = gzip.open(path, "rt", errors="replace").read() if path.endswith(".gz") else open(path, errors="replace").read()
    out = []
    for line in raw.splitlines():
        if line.startswith((".\\\"", "'\\\"")):
            continue  # comment
        if line.startswith("."):
            parts = line.split(None, 1)
            line = parts[1] if len(parts) > 1 else ""  # macro arguments are text (.SH NAME, .B word)
        line = re.sub(r"\\f[BIRP]|\\f\(..|\\\(..|\\\*.|\\[&|^%-]|\\e", " ", line)
        out.append(line)
    return "\n".join(out)

counts = collections.Counter()
for sec in ("man1", "man5", "man7", "man8"):
    d = os.path.join(MAN, sec)
    for name in sorted(os.listdir(d)) if os.path.isdir(d) else []:
        path = os.path.join(d, name)
        if os.path.islink(path) or not os.path.isfile(path):
            continue  # aliases and dangling links
        for w in WORD.findall(text_of(path)):
            if len(w) >= 2 and (w.islower() or w[1:].islower()):
                counts[w.lower()] += 1
total = sum(counts.values())
rows = sorted((w, round(10 * math.log10(c * 1e6 / total))) for w, c in counts.items() if c >= MIN_COUNT)
print("// SPDX-License-Identifier: GPL-3.0-or-later")
print("// Generated by engine-rs/tools/gen_tech_english.py from the English manual pages (sections 1, 5,")
print(f"// 7, 8; {total} words, words seen at least {MIN_COUNT} times). Do not edit.")
print("// Scores: 10*log10(occurrences per million), the scale of the Vikey lists.")
print()
print(f"pub static TECH_WORDS: [(&str, i8); {len(rows)}] = [")
for w, s in rows:
    print(f'    ("{w}", {s}),')
print("];")
